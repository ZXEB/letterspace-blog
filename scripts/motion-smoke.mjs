import fs from 'node:fs'
import {openBrowser,uiDir} from './browser.mjs'

const origin=process.env.BLOG_ORIGIN || 'http://localhost:18080'
const checks=[]
const assert=(ok,message)=>{if(!ok)throw Error(message);checks.push(message)}
const {context,close}=await openBrowser('motion-acceptance')
const errors=[]
let page
try{
  page=await context.newPage();page.on('pageerror',e=>errors.push(e.message))
  await page.emulateMedia({reducedMotion:'no-preference',colorScheme:'light'})
  await page.addInitScript(()=>localStorage.setItem('letterspace-theme','light'))
  await page.goto(origin,{waitUntil:'domcontentloaded'})
  await page.locator('.hero-line').first().waitFor()
  const heroAnimations=await page.evaluate(()=>document.getAnimations().filter(a=>a.animationName?.includes('arrive')).map(a=>a.animationName))
  assert(heroAnimations.includes('line-arrive')&&heroAnimations.includes('avatar-arrive'),'Hero has staggered text and avatar entrance animations')
  await page.waitForTimeout(260)
  await page.screenshot({path:uiDir+'/motion-hero-entering.png'})
  await page.waitForTimeout(1600)
  assert(await page.locator('.hero-line').first().evaluate(e=>getComputedStyle(e).opacity)==='1','Hero settles at full opacity')
  const nav=page.locator('#site-navigation')
  const pill=nav.locator('.nav-indicator')
  const before=await pill.evaluate(e=>getComputedStyle(e).transform)
  await nav.getByRole('link',{name:'文稿',exact:true}).hover()
  await page.waitForTimeout(100)
  const middle=await pill.evaluate(e=>getComputedStyle(e).transform)
  await page.waitForTimeout(500)
  const after=await pill.evaluate(e=>getComputedStyle(e).transform)
  assert(before!==middle&&middle!==after&&after!==before,'Navigation highlight moves through intermediate frames')
  await page.mouse.move(30,300);await page.waitForTimeout(550)
  assert(await pill.evaluate(e=>getComputedStyle(e).transform)===before,'Navigation highlight returns to the active route')
  await page.locator('.writing-row').first().waitFor()
  await page.evaluate(()=>window.scrollTo({top:document.querySelector('#recent').getBoundingClientRect().top+scrollY-240,behavior:'instant'}))
  await page.waitForTimeout(100)
  const reveal=await page.locator('.writing-row').nth(3).evaluate(e=>e.getAnimations().some(a=>a.playState==='running'))
  assert(reveal,'Recent articles animate when scrolled into view')
  await page.screenshot({path:uiDir+'/motion-list-entering.png'})
  await page.waitForTimeout(1000)
  await page.locator('.writing-row').first().hover();await page.waitForTimeout(450)
  assert(await page.locator('.row-copy').first().evaluate(e=>getComputedStyle(e).transform)!=='none','Article hover has a measured movement response')
  await page.locator('.writing-activity').scrollIntoViewIfNeeded();await page.waitForTimeout(120)
  assert(await page.locator('.writing-activity').getAttribute('data-revealed')==='true','Publication line activates on scroll')
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));await page.waitForTimeout(100)
  await page.getByRole('button',{name:'切换主题'}).click()
  await page.waitForTimeout(100)
  if(await page.evaluate(()=>Boolean(document.startViewTransition))) assert(await page.locator('html').evaluate(e=>e.classList.contains('theme-changing')),'Theme change uses a circular view transition')
  await page.waitForTimeout(850)
  assert(await page.locator('html').getAttribute('data-theme')==='dark','Theme transition ends in dark mode')
  assert(!await page.locator('html').evaluate(e=>e.classList.contains('theme-changing')),'Theme transition releases its overlay')
  await page.screenshot({path:uiDir+'/motion-dark.png',fullPage:true,animations:'disabled'})
  await nav.getByRole('link',{name:'文稿',exact:true}).click()
  await page.locator('.archive-card').first().waitFor();await page.waitForTimeout(850)
  await page.locator('.archive-list .archive-title').first().click();await page.locator('.prose').waitFor();await page.waitForTimeout(900)
  assert(await page.locator('.prose').innerText().then(t=>t.length>20),'Animated article navigation still loads real content')
  await page.setViewportSize({width:390,height:600})
  await page.evaluate(()=>window.scrollTo({top:document.documentElement.scrollHeight,behavior:'instant'}));await page.waitForTimeout(200)
  assert(await page.locator('.reading-progress').evaluate(e=>getComputedStyle(e).transform)!=='matrix(0, 0, 0, 1, 0, 0)','Reading progress responds to scroll')
  await page.getByRole('button',{name:'打开菜单',exact:true}).click();await page.waitForTimeout(100)
  const opening=await nav.evaluate(e=>Number(getComputedStyle(e).opacity))
  assert(opening>0&&opening<1,'Mobile menu opens through intermediate frames')
  await page.waitForTimeout(350)
  assert(await page.getByRole('button',{name:'关闭菜单',exact:true}).getAttribute('aria-expanded')==='true','Mobile menu exposes its expanded state')
  await nav.getByRole('link',{name:'首页',exact:true}).click();await page.waitForTimeout(500)
  assert(await nav.evaluate(e=>getComputedStyle(e).visibility)==='hidden','Mobile navigation closes after route change')
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Motion creates no horizontal overflow on mobile')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.reload({waitUntil:'domcontentloaded'});await page.locator('.writing-row').first().waitFor();await page.waitForTimeout(300)
  assert(await page.evaluate(()=>document.getAnimations().filter(a=>a.playState==='running').length)===0,'Reduced-motion preference disables entry and looping animations')
  await page.getByRole('button',{name:'切换主题'}).click();await page.waitForTimeout(50)
  assert(!await page.locator('html').evaluate(e=>e.classList.contains('theme-changing')),'Reduced-motion theme change skips the circular animation')
  assert(await page.locator('.hero-line').first().evaluate(e=>getComputedStyle(e).opacity)==='1','Reduced-motion content remains fully readable')
  await page.screenshot({path:uiDir+'/motion-mobile.png',fullPage:true,animations:'disabled'})
  assert(errors.length===0,'No uncaught browser errors during motion flows')
  const report={date:new Date().toISOString(),origin,passed:checks.length,checks,heroAnimations,screenshots:['motion-hero-entering.png','motion-list-entering.png','motion-dark.png','motion-mobile.png']}
  fs.writeFileSync(uiDir+'/motion-acceptance-report.json',JSON.stringify(report,null,2))
  console.log(JSON.stringify({passed:checks.length,report:uiDir+'/motion-acceptance-report.json'}))
}catch(error){if(page)await page.screenshot({path:uiDir+'/motion-failure.png'}).catch(()=>{});fs.writeFileSync(uiDir+'/motion-failure.json',JSON.stringify({error:error.message,checks,errors},null,2));throw error}finally{await close()}
